#!/usr/bin/env python3
"""Build the P2 bank manifest (stdlib only, Python 3.12).

Input:  benchmarks/p2_bank_entries.tsv (no hashes)
        <audio-dir>/<audio_file> for every row (real sherpa output)
Output: benchmarks/p2_bank_manifest.tsv with audio_sha256.

The manifest is the only file the runtime trusts: it binds a line to its event
type, exact public fact, speaker, persona, sid and audio hash. A missing file or
a sid/speaker mismatch is a hard error so a bank cannot silently ship a wrong
voice.
"""
from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

ENTRY_HEADER = [
    "line_id", "event_type", "fact_key", "speaker", "persona_id", "emotion",
    "text", "tts_sid", "audio_file", "weight",
]
SID_FOR_SPEAKER = {1: 8, 2: 9, 3: 10}


def read_rows(path: pathlib.Path) -> list[list[str]]:
    rows = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != len(ENTRY_HEADER):
            raise SystemExit(f"{path}:{number}: expected {len(ENTRY_HEADER)} columns, got {len(fields)}")
        rows.append(fields)
    return rows


def sha256_file(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Build the P2 bank manifest.")
    parser.add_argument("--entries", default=str(pathlib.Path(__file__).with_name("p2_bank_entries.tsv")))
    parser.add_argument("--audio-dir", required=True,
                        help="directory containing the WAVs named in audio_file")
    parser.add_argument("--out", default=str(pathlib.Path(__file__).with_name("p2_bank_manifest.tsv")))
    args = parser.parse_args(argv)
    entries = pathlib.Path(args.entries).resolve()
    audio_dir = pathlib.Path(args.audio_dir).resolve()
    out = pathlib.Path(args.out).resolve()
    if not entries.is_file():
        raise SystemExit(f"entries not found: {entries}")
    if not audio_dir.is_dir():
        raise SystemExit(f"audio dir not found: {audio_dir}")

    rows = read_rows(entries)
    seen: set[str] = set()
    lines = ["# UTF-8 TSV, no header. Generated by benchmarks/p2_bank_build.py.",
             "# Columns: " + ", ".join(ENTRY_HEADER[:-1] + ["audio_sha256", "weight"])]
    for row in rows:
        line_id, event_type, fact_key, speaker, persona, emotion, text, sid, audio_file, weight = row
        if line_id in seen:
            raise SystemExit(f"duplicate line_id: {line_id}")
        seen.add(line_id)
        speaker_i, sid_i = int(speaker), int(sid)
        if SID_FOR_SPEAKER.get(speaker_i) != sid_i:
            raise SystemExit(f"{line_id}: sid {sid_i} does not match speaker {speaker_i}")
        audio = audio_dir / audio_file
        if not audio.is_file():
            raise SystemExit(f"{line_id}: missing audio {audio}")
        lines.append("\t".join([line_id, event_type, fact_key, speaker, persona, emotion,
                                text, sid, audio_file, sha256_file(audio), weight]))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(rows)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
